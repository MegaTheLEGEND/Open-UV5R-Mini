#!/usr/bin/env python3
"""Turn the stock app.bin into assembly source that the open toolchain rebuilds byte for byte.

usage:
  python tools/mkasm.py firmware/stock/app.bin --isa ../pi32v2-isa \
      --toolchain E:/toolchains/pi32v2-llvm/bin -o build/stock/app.S

Every position of a linear sweep is written as its instruction text when clang assembles that text back to the
very same bytes, and as a `.byte` line otherwise (data, block openers, parallel pairs, non-shortest encodings,
undecodable words). The generated source is derived from Baofeng's firmware: it stays in build/ and is never
committed. Bring your own .ufw.

Named functions from tools/symbols.txt become labels, so the listing reads like a source file.
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile

BASE = 0x01E00100
LINE_RE = re.compile(r'^L(\d+)$')


def load_isa(path):
    sys.path.insert(0, os.path.abspath(path))
    from pi32v2isa import table, codec
    return table.load(os.path.join(path, 'isa', 'pi32v2.toml')), codec


def sweep(t, codec, data):
    off = 0
    while off < len(data):
        got = codec.decode(t, data, off) if off + 1 < len(data) else None
        if got is None:
            n = min(2, len(data) - off)
            yield off, n, None
        else:
            insn, values, n = got
            yield off, n, codec.format(insn, values)
        off += n


def usable(text):
    """Texts worth trying: no block bodies, no parallel markers."""
    return text is not None and '{' not in text and not text.rstrip().endswith('#') and '}' not in text


def assemble_unique(texts, tc):
    """Return {text: bytes} for every text clang assembles; texts it rejects are left out."""
    texts = list(texts)
    good = {}
    with tempfile.TemporaryDirectory() as tmp:
        src, obj, raw = (os.path.join(tmp, n) for n in ('u.S', 'u.o', 'u.bin'))
        pending = texts
        for _round in range(40):
            with open(src, 'w') as f:
                f.write('\t.section .text,"ax"\n')
                for i, t in enumerate(pending):
                    f.write('L%d:\t%s\n' % (i, t))
                f.write('L%d:\n' % len(pending))
            r = subprocess.run([os.path.join(tc, 'clang'), '--target=pi32v2', '-c', src, '-o', obj],
                               capture_output=True, text=True)
            if r.returncode != 0:
                bad = set()
                for m in re.finditer(r'u\.S:(\d+):\d+: error', r.stderr):
                    bad.add(int(m.group(1)) - 2)   # line 1 is .section, line k+2 is text k
                if not bad:
                    raise SystemExit('clang failed without line numbers:\n' + r.stderr[:2000])
                pending = [t for i, t in enumerate(pending) if i not in bad]
                continue
            subprocess.run([os.path.join(tc, 'llvm-objcopy'), '-O', 'binary', '-j', '.text', obj, raw], check=True)
            code = open(raw, 'rb').read()
            nm = subprocess.run([os.path.join(tc, 'llvm-nm'), obj], capture_output=True, text=True, check=True)
            addr = {}
            for line in nm.stdout.splitlines():
                parts = line.split()
                if len(parts) == 3 and LINE_RE.match(parts[2]):
                    addr[int(LINE_RE.match(parts[2]).group(1))] = int(parts[0], 16)
            for i, t in enumerate(pending):
                good[t] = code[addr[i]:addr[i + 1]]
            return good
    raise SystemExit('too many assembler error rounds')


def load_symbols(path):
    syms = {}
    if path and os.path.exists(path):
        for line in open(path, encoding='utf-8'):
            line = line.split('#')[0].strip()
            if line:
                a, name = line.split()[:2]
                syms[int(a, 16)] = name
    return syms


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('app')
    ap.add_argument('--isa', required=True)
    ap.add_argument('--toolchain', required=True)
    ap.add_argument('--symbols', default=os.path.join(os.path.dirname(__file__), 'symbols.txt'))
    ap.add_argument('-o', '--out', required=True)
    a = ap.parse_args()

    t, codec = load_isa(a.isa)
    data = open(a.app, 'rb').read()
    items = list(sweep(t, codec, data))
    uniq = {text for _, _, text in items if usable(text)}
    print('%d positions, %d distinct candidate texts' % (len(items), len(uniq)))
    enc = assemble_unique(uniq, a.toolchain)
    syms = load_symbols(a.symbols)

    as_text = as_bytes = 0
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, 'w', encoding='utf-8') as f:
        f.write('/* Generated by tools/mkasm.py from the stock UV-5R Mini app.bin. Do not commit: derived from\n'
                '   Baofeng firmware. Rebuilds byte for byte with clang + ld.lld (see docs/MATCHING.md). */\n')
        f.write('\t.section .stock_app,"ax"\n\t.globl stock_app_start\nstock_app_start:\n')
        for off, n, text in items:
            addr = BASE + off
            if addr in syms:
                f.write('\n\t.globl %s\n%s:\n' % (syms[addr], syms[addr]))
            raw = data[off:off + n]
            if text is not None and enc.get(text) == raw:
                f.write('\t%s\t\t/* %08x */\n' % (text, addr))
                as_text += 1
            else:
                f.write('\t.byte %s\t\t/* %08x%s */\n' % (', '.join('0x%02x' % b for b in raw), addr,
                                                          ': ' + text if text else ''))
                as_bytes += 1
    print('wrote %s: %d instructions as text, %d as .byte' % (a.out, as_text, as_bytes))


if __name__ == '__main__':
    main()
