#!/usr/bin/env python3
"""Turn the pixel-art assets in assets/ into C for the firmware (src/ui/icons.c, src/ui/icons.h).

Icons are plain text, one file each: assets/icons/<group>_<name>.txt (docs/LAYOUT.md has the naming rules).
  - '#' is a lit pixel, '.' is off; every row the same width; at most 32 x 32.
  - Lines starting with '//' are comments (say what the icon shows); blank lines are ignored.
The C name is ICON_<GROUP>_<NAME> in upper case. Icons are 1 bit: the firmware draws them in any two colours
(UI_DrawIcon in src/ui/helper.c), so one file serves every colour state.

  python tools/mkassets.py           # write src/ui/icons.c and src/ui/icons.h
  python tools/mkassets.py --check   # exit 1 if they are out of date (make check runs this)
"""
import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ICON_DIR = os.path.join(ROOT, 'assets', 'icons')
OUT_C = os.path.join(ROOT, 'src', 'ui', 'icons.c')
OUT_H = os.path.join(ROOT, 'src', 'ui', 'icons.h')
NAME_RE = re.compile(r'^[a-z][a-z0-9]*(_[a-z0-9]+)+$')
HEADER = '/* Generated by tools/mkassets.py from assets/icons/. Do not edit: change the .txt file and run it again. */\n'


def load_icon(path):
    rows, notes = [], []
    with open(path, encoding='utf-8') as f:
        for n, line in enumerate(f, 1):
            line = line.rstrip('\r\n')
            if line.startswith('//'):
                notes.append(line[2:].strip())
                continue
            if not line.strip():
                continue
            if set(line) - set('#.'):
                raise SystemExit('%s:%d: only "#" and "." are allowed in a row' % (path, n))
            rows.append(line)
    if not rows:
        raise SystemExit('%s: no pixel rows' % path)
    w = len(rows[0])
    if any(len(r) != w for r in rows):
        raise SystemExit('%s: rows have different widths' % path)
    if w > 32 or len(rows) > 32:
        raise SystemExit('%s: larger than 32 x 32' % path)
    return rows, ' '.join(notes)


def render():
    icons = []
    for fn in sorted(os.listdir(ICON_DIR)):
        if not fn.endswith('.txt'):
            continue
        name = fn[:-4]
        if not NAME_RE.match(name):
            raise SystemExit('%s: name must be <group>_<name>, lower case, digits and "_" only' % fn)
        rows, note = load_icon(os.path.join(ICON_DIR, fn))
        icons.append((name, rows, note))

    h = [HEADER, '#ifndef UI_ICONS_H\n#define UI_ICONS_H\n\n#include <stdint.h>\n\n',
         '/* One icon: w x h pixels, rows top to bottom, each row (w + 7) / 8 bytes, most significant bit = leftmost. */\n',
         'typedef struct {\n\tuint8_t w, h;\n\tconst uint8_t *bits;\n} Icon_t;\n\n']
    c = [HEADER, '#include "ui/icons.h"\n']
    for name, rows, note in icons:
        sym = 'ICON_' + name.upper()
        w, ht = len(rows[0]), len(rows)
        data = []
        for r in rows:
            for b in range(0, w, 8):
                chunk = r[b:b + 8].ljust(8, '.')
                data.append(int(chunk.replace('#', '1').replace('.', '0'), 2))
        h.append('extern const Icon_t %s;%s\n' % (sym, ('   /* %dx%d: %s */' % (w, ht, note)) if note else ''))
        c.append('\nstatic const uint8_t %s_BITS[] = {%s};\n' % (sym, ', '.join('0x%02X' % d for d in data)))
        c.append('const Icon_t %s = { %d, %d, %s_BITS };\n' % (sym, w, ht, sym))
    h.append('\n#endif\n')
    return ''.join(c), ''.join(h)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true', help='only check the generated files are up to date')
    a = ap.parse_args()
    c, h = render()
    if a.check:
        stale = [p for p, t in ((OUT_C, c), (OUT_H, h))
                 if not os.path.exists(p) or open(p, encoding='utf-8').read() != t]
        if stale:
            print('out of date: %s (run python tools/mkassets.py)' % ', '.join(os.path.relpath(p, ROOT) for p in stale))
            return 1
        print('assets: up to date')
        return 0
    for p, t in ((OUT_C, c), (OUT_H, h)):
        with open(p, 'w', encoding='utf-8', newline='\n') as f:
            f.write(t)
    print('wrote %s, %s' % (os.path.relpath(OUT_C, ROOT), os.path.relpath(OUT_H, ROOT)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
